CREATE TABLE tbl_notices (
    notice_id bigint GENERATED BY DEFAULT AS IDENTITY,
    title character varying(255) NOT NULL,
    content text NOT NULL,
    author_id bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT tbl_notices_pkey PRIMARY KEY (notice_id)
);

ALTER TABLE tbl_notices ADD CONSTRAINT fk_notices_author FOREIGN KEY (author_id) REFERENCES tbl_users (user_id);

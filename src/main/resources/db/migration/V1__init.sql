-- 문제 랭크
CREATE TABLE tbl_problem_ranks (
    problem_rank_id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(255) NOT NULL,
    xp bigint NOT NULL,
    CONSTRAINT tbl_problem_ranks_pkey PRIMARY KEY (problem_rank_id),
    CONSTRAINT ukneo5n2fdm6a8ee3mkuhoqqjaf UNIQUE (name)
);

-- 유저
CREATE TABLE tbl_users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) without time zone NOT NULL,
    email character varying(320) NOT NULL,
    name character varying(255) NOT NULL,
    password character varying(60) NOT NULL,
    phone_number character(15),
    role character varying(255) NOT NULL,
    xp bigint NOT NULL,
    updated_at timestamp(6) without time zone NOT NULL,
    user_rank_id bigint NOT NULL,
    CONSTRAINT tbl_users_pkey PRIMARY KEY (user_id),
    CONSTRAINT ukj562wwmipqt96rkoqbo0jc34 UNIQUE (email),
    CONSTRAINT tbl_users_role_check CHECK (role IN ('STUDENT', 'TEACHER'))
);

CREATE TABLE tbl_students (
    user_id bigint NOT NULL,
    class_number smallint NOT NULL,
    grade smallint NOT NULL,
    student_number smallint NOT NULL,
    CONSTRAINT tbl_students_pkey PRIMARY KEY (user_id)
);

CREATE TABLE tbl_streaks (
    user_id bigint NOT NULL,
    current_streak integer NOT NULL,
    max_streak integer NOT NULL,
    last_solved_date date,
    CONSTRAINT tbl_streaks_pkey PRIMARY KEY (user_id)
);

-- 문제
CREATE TABLE tbl_categories (
    category_id bigint GENERATED BY DEFAULT AS IDENTITY,
    name character varying(255) NOT NULL,
    CONSTRAINT tbl_categories_pkey PRIMARY KEY (category_id),
    CONSTRAINT ukpnqt0pl545ljtiykhqj1egymh UNIQUE (name)
);

CREATE TABLE tbl_problems (
    problem_id bigint GENERATED BY DEFAULT AS IDENTITY,
    content text NOT NULL,
    memory_limit bigint NOT NULL,
    time_limit double precision NOT NULL,
    title character varying(255) NOT NULL,
    problem_rank_id bigint NOT NULL,
    CONSTRAINT tbl_problems_pkey PRIMARY KEY (problem_id),
    CONSTRAINT ukbu6xljqliywwbwconemeb8i UNIQUE (title)
);

CREATE TABLE tbl_problem_categories (
    category_id bigint NOT NULL,
    problem_id bigint NOT NULL,
    CONSTRAINT tbl_problem_categories_pkey PRIMARY KEY (category_id, problem_id)
);

CREATE TABLE tbl_testcases (
    testcase_id bigint GENERATED BY DEFAULT AS IDENTITY,
    example_read text,
    example_write text NOT NULL,
    is_sample boolean NOT NULL,
    problem_id bigint NOT NULL,
    CONSTRAINT tbl_testcases_pkey PRIMARY KEY (testcase_id)
);

-- 제출
CREATE TABLE tbl_solutions (
    solution_id bigint GENERATED BY DEFAULT AS IDENTITY,
    code text NOT NULL,
    language character varying(255) NOT NULL,
    memory_used bigint,
    status character varying(255) NOT NULL,
    "time" double precision,
    problem_id bigint NOT NULL,
    user_id bigint NOT NULL,
    submitted_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT tbl_solutions_pkey PRIMARY KEY (solution_id),
    CONSTRAINT tbl_solutions_language_check CHECK (language IN ('C99', 'CPP17', 'JAVA', 'PYTHON', 'JAVASCRIPT', 'TEXT')),
    CONSTRAINT tbl_solutions_status_check CHECK (status IN ('PENDING', 'ACCEPTED', 'WRONG_ANSWER', 'TIME_LIMIT_EXCEEDED', 'RUNTIME_ERROR', 'COMPILE_ERROR', 'INTERNAL_ERROR'))
);

CREATE TABLE tbl_solved_histories (
    solved_time timestamp(6) without time zone NOT NULL,
    problem_id bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT tbl_solved_histories_pkey PRIMARY KEY (problem_id, user_id)
);

-- XP / 퀘스트
CREATE TABLE tbl_xp_histories (
    xp_history_id bigint GENERATED BY DEFAULT AS IDENTITY,
    amount bigint NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    problem_id bigint,
    problem_title character varying(255),
    reason text NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT tbl_xp_histories_pkey PRIMARY KEY (xp_history_id)
);

CREATE TABLE tbl_quest_rewards (
    quest_reward_id bigint GENERATED BY DEFAULT AS IDENTITY,
    quest character varying(255) NOT NULL,
    quest_date date NOT NULL,
    rewarded_at timestamp(6) without time zone NOT NULL,
    xp bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT tbl_quest_rewards_pkey PRIMARY KEY (quest_reward_id),
    CONSTRAINT uk_quest_rewards_user_date_quest UNIQUE (user_id, quest_date, quest),
    CONSTRAINT tbl_quest_rewards_quest_check CHECK (quest IN (
        'SOLVE_1', 'SOLVE_2', 'SUBMIT_1', 'SUBMIT_3', 'ACCEPTED_1', 'SOLVE_1_RANK_2_OR_ABOVE',
        'SOLVE_3', 'SUBMIT_5', 'ACCEPTED_3', 'SOLVE_2_RANK_2_OR_ABOVE', 'SOLVE_1_RANK_3_OR_ABOVE', 'SOLVE_2_RANK_KINDS',
        'SOLVE_5', 'SOLVE_2_RANK_3_OR_ABOVE', 'SOLVE_1_RANK_4_OR_ABOVE', 'SOLVE_1_TOP_RANK', 'ACCEPTED_2_LANGUAGES'
    ))
);

-- 소셜
CREATE TABLE tbl_friendships (
    friendship_id bigint GENERATED BY DEFAULT AS IDENTITY,
    accepted_at timestamp(6) without time zone,
    created_at timestamp(6) without time zone NOT NULL,
    status character varying(255) NOT NULL,
    receiver_id bigint NOT NULL,
    requester_id bigint NOT NULL,
    CONSTRAINT tbl_friendships_pkey PRIMARY KEY (friendship_id),
    CONSTRAINT tbl_friendships_status_check CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED'))
);

CREATE TABLE tbl_groups (
    group_id bigint GENERATED BY DEFAULT AS IDENTITY,
    introduce character varying(255),
    title character varying(255) NOT NULL,
    created_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT tbl_groups_pkey PRIMARY KEY (group_id)
);

CREATE TABLE tbl_group_members (
    group_id bigint NOT NULL,
    user_id bigint NOT NULL,
    joined_at timestamp(6) without time zone NOT NULL,
    role character varying(255) NOT NULL,
    CONSTRAINT tbl_group_members_pkey PRIMARY KEY (group_id, user_id),
    CONSTRAINT tbl_group_members_role_check CHECK (role IN ('OWNER', 'MEMBER'))
);

CREATE TABLE tbl_group_invitations (
    invitation_id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) without time zone NOT NULL,
    expires_at timestamp(6) without time zone NOT NULL,
    status character varying(255) NOT NULL,
    group_id bigint NOT NULL,
    invitee_id bigint NOT NULL,
    inviter_id bigint NOT NULL,
    CONSTRAINT tbl_group_invitations_pkey PRIMARY KEY (invitation_id),
    CONSTRAINT tbl_group_invitations_status_check CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELED', 'EXPIRED'))
);


-- 인덱스
CREATE INDEX idx_xp_histories_user_created ON tbl_xp_histories (user_id, created_at);

-- 랭크 이름으로 조회하므로 중복되면 안 된다
CREATE UNIQUE INDEX uk_user_ranks_name ON tbl_user_ranks (name);

-- 두 유저 사이에는 방향과 상관없이 대기 중이거나 수락된 친구 관계가 하나만 존재한다
CREATE UNIQUE INDEX uk_friendships_active_pair
    ON tbl_friendships (LEAST(requester_id, receiver_id), GREATEST(requester_id, receiver_id))
    WHERE status IN ('PENDING', 'ACCEPTED');

-- 한 그룹에서 같은 유저에게 대기 중인 초대는 하나만 존재한다
CREATE UNIQUE INDEX uk_group_invitations_pending
    ON tbl_group_invitations (group_id, invitee_id)
    WHERE status = 'PENDING';

-- 한 그룹의 그룹장은 한 명만 존재한다
CREATE UNIQUE INDEX uk_group_members_owner
    ON tbl_group_members (group_id)
    WHERE role = 'OWNER';

